def font_run(run, size=10.5, bold=False, color=None):
    run.font.name='Microsoft YaHei'; run._element.rPr.rFonts.set(qn('w:eastAsia'),'Microsoft YaHei'); run.font.size=Pt(size); run.bold=bold
    if color: run.font.color.rgb=RGBColor.from_string(color)

def shade(cell, fill):
    tcPr=cell._tc.get_or_add_tcPr(); shd=tcPr.find(qn('w:shd'))
    if shd is None: shd=OxmlElement('w:shd'); tcPr.append(shd)
    shd.set(qn('w:fill'),fill)

def border(cell, color='D9E2F3', sz='4'):
    tcPr=cell._tc.get_or_add_tcPr(); bs=tcPr.first_child_found_in('w:tcBorders')
    if bs is None: bs=OxmlElement('w:tcBorders'); tcPr.append(bs)
    for edge in ('top','left','bottom','right'):
        el=bs.find(qn('w:'+edge))
        if el is None: el=OxmlElement('w:'+edge); bs.append(el)
        el.set(qn('w:val'),'single'); el.set(qn('w:sz'),sz); el.set(qn('w:color'),color)

def cell_text(cell, text, bold=False, size=8.8, color=None):
    cell.text=''; p=cell.paragraphs[0]; p.paragraph_format.space_after=Pt(1); p.paragraph_format.line_spacing=1.05
    r=p.add_run(str(text)); font_run(r,size,bold,color); cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER; border(cell)

def table(doc, headers, rows, widths=None, size=8.8):
    t=doc.add_table(rows=1, cols=len(headers)); t.style='Table Grid'; t.alignment=WD_TABLE_ALIGNMENT.CENTER
    for i,h in enumerate(headers): cell_text(t.rows[0].cells[i],h,True,size,'FFFFFF'); shade(t.rows[0].cells[i],'1F4E79')
    for idx,row in enumerate(rows):
        cells=t.add_row().cells
        for i,val in enumerate(row):
            cell_text(cells[i],val,False,size)
            if idx%2==0: shade(cells[i],'F4F7FA')
    if widths:
        for row in t.rows:
            for i,w in enumerate(widths): row.cells[i].width=Inches(w)
    doc.add_paragraph().paragraph_format.space_after=Pt(0)
    return t

def para(doc, text, size=10.5, bold_prefix=None):
    p=doc.add_paragraph(); p.paragraph_format.space_after=Pt(5); p.paragraph_format.line_spacing=1.18
    if bold_prefix and text.startswith(bold_prefix):
        r=p.add_run(bold_prefix); font_run(r,size,True)
        r=p.add_run(text[len(bold_prefix):]); font_run(r,size)
    else:
        r=p.add_run(text); font_run(r,size)
    return p

def bullets(doc, items, level=0):
    for item in items:
        p=doc.add_paragraph(style='List Bullet' if level==0 else 'List Bullet 2'); p.paragraph_format.space_after=Pt(2); p.paragraph_format.line_spacing=1.12
        r=p.add_run(item); font_run(r,10.3)

def callout(doc, label, text, fill='FFF2CC', color='7F6000'):
    t=doc.add_table(rows=1, cols=1); c=t.cell(0,0); shade(c,fill); border(c,'D6B656','8'); c.text=''
    p=c.paragraphs[0]; p.paragraph_format.space_after=Pt(0); p.paragraph_format.line_spacing=1.1
    r=p.add_run(label+'：'); font_run(r,9.8,True,color); r=p.add_run(text); font_run(r,9.8,False,color)
    doc.add_paragraph().paragraph_format.space_after=Pt(0)

